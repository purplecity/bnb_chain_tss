package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"

	"github.com/purplecity/bnb_chain_tss/task3-address/derive"
)

func main() {
	metaPath := flag.String("wallet-meta", "", "wallet.json generated by task1-keygen")
	siteID := flag.Uint("site-id", 0, "non-hardened numeric site slot (0 <= id < 2^31)")
	index := flag.Uint("index", 0, "non-hardened user/address index (0 <= index < 2^31)")
	flag.Parse()
	if *metaPath == "" {
		fatal("--wallet-meta is required")
	}
	b, err := os.ReadFile(*metaPath)
	if err != nil {
		fatal("read wallet metadata: %v", err)
	}
	var meta derive.WalletMeta
	if err := json.Unmarshal(b, &meta); err != nil {
		fatal("parse wallet metadata: %v", err)
	}
	result, _, err := derive.Derive(meta, uint32(*siteID), uint32(*index))
	if err != nil {
		fatal("derive address: %v", err)
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(result); err != nil {
		fatal("write result: %v", err)
	}
}

func fatal(format string, args ...any) { fmt.Fprintf(os.Stderr, format+"\n", args...); os.Exit(1) }
